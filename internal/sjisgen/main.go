// Command sjisgen generates the Shift-JIS mapping table used by the qrcode
// package for Kanji mode. It is a nested module so that its dependency on
// golang.org/x/text never reaches the library itself.
//
// Regenerate with:
//
//	cd internal/sjisgen && go run . > ../../sjis_table.go
package main

import (
	"bufio"
	"fmt"
	"os"
	"sort"

	"golang.org/x/text/encoding/japanese"
)

type entry struct {
	r rune
	c uint16
}

func main() {
	enc := japanese.ShiftJIS.NewEncoder()
	dec := japanese.ShiftJIS.NewDecoder()

	var entries []entry
	for r := rune(0x00A0); r <= 0xFFFF; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue // surrogate range
		}
		s := string(r)
		out, err := enc.Bytes([]byte(s))
		if err != nil || len(out) != 2 {
			continue // only double-byte JIS X 0208 characters suit Kanji mode
		}
		back, err := dec.Bytes(out)
		if err != nil || string(back) != s {
			continue
		}
		entries = append(entries, entry{r, uint16(out[0])<<8 | uint16(out[1])})
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].r < entries[j].r })

	w := bufio.NewWriter(os.Stdout)
	defer w.Flush()

	fmt.Fprintln(w, "package qrcode")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "// Code generated by internal/sjisgen. DO NOT EDIT.")
	fmt.Fprintln(w, "//")
	fmt.Fprintln(w, "// sjisTable maps JIS X 0208 code points to their two-byte Shift-JIS")
	fmt.Fprintln(w, "// encoding, sorted by code point for binary search. Each entry packs the")
	fmt.Fprintln(w, "// code point in the high 16 bits and the Shift-JIS code in the low 16.")
	fmt.Fprintf(w, "\nvar sjisTable = [%d]uint32{\n", len(entries))
	for _, e := range entries {
		fmt.Fprintf(w, "\t0x%04X%04X,\n", e.r, e.c)
	}
	fmt.Fprintln(w, "}")
}
